"""Database models for Crave."""

from datetime import date, datetime
from uuid import UUID, uuid4

from sqlalchemy import Boolean, CheckConstraint, Column, Date, DateTime, Enum, Float, ForeignKey, Index, Integer, String, Table, Text, Uuid, func
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

from app.recipe_enums import Difficulty, RecipeType


class Base(DeclarativeBase):
    pass


recipe_tags = Table(
    "recipe_tags",
    Base.metadata,
    Column("recipe_id", Uuid, ForeignKey("recipes.id", ondelete="CASCADE"), primary_key=True),
    Column("tag_id", Uuid, ForeignKey("tags.id", ondelete="CASCADE"), primary_key=True),
)


class Tag(Base):
    __tablename__ = "tags"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    name: Mapped[str] = mapped_column(String(80), unique=True, nullable=False)
    recipes: Mapped[list["Recipe"]] = relationship(secondary=recipe_tags, back_populates="tags")


class Recipe(Base):
    __tablename__ = "recipes"
    __table_args__ = (
        CheckConstraint("total_time_minutes >= 0", name="ck_recipes_total_time_nonnegative"),
        CheckConstraint("calories >= 0", name="ck_recipes_calories_nonnegative"),
        CheckConstraint("protein_g >= 0 AND carbs_g >= 0 AND fat_g >= 0", name="ck_recipes_macros_nonnegative"),
        Index("ix_recipes_type_difficulty_time", "recipe_type", "difficulty", "total_time_minutes"),
    )

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    # Every recipe belongs to exactly one account. Nullable only so the column can be added to
    # existing databases; rows without an owner are invisible to every user.
    owner_id: Mapped[str | None] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), index=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    description: Mapped[str] = mapped_column(Text, nullable=False)
    recipe_type: Mapped[RecipeType] = mapped_column(Enum(RecipeType, name="recipe_type"), nullable=False, index=True)
    # image-1 output is stored as a data URL until object storage is introduced.
    image_data: Mapped[str | None] = mapped_column(Text)
    # Downscaled JPEG data URL derived from image_data; used by list views (see app.thumbnails).
    thumbnail_data: Mapped[str | None] = mapped_column(Text)
    servings: Mapped[int] = mapped_column(Integer, nullable=False)
    total_time_minutes: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    difficulty: Mapped[Difficulty] = mapped_column(Enum(Difficulty, name="difficulty"), nullable=False, index=True)
    calories: Mapped[int] = mapped_column(Integer, nullable=False, index=True)
    protein_g: Mapped[float] = mapped_column(Float, nullable=False, index=True)
    carbs_g: Mapped[float] = mapped_column(Float, nullable=False, index=True)
    fat_g: Mapped[float] = mapped_column(Float, nullable=False, index=True)
    ingredients: Mapped[list[dict[str, object]]] = mapped_column(JSONB, nullable=False)
    instructions: Mapped[list[str]] = mapped_column(JSONB, nullable=False)
    details: Mapped[dict[str, object]] = mapped_column(JSONB, nullable=False)
    is_ai_generated: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, server_default="false", index=True)
    # Values from app.recipe_enums.Appliance; plain string so new machines need no enum migration.
    appliance: Mapped[str] = mapped_column(String(20), nullable=False, default="none", server_default="none")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    tags: Mapped[list[Tag]] = relationship(secondary=recipe_tags, back_populates="recipes", lazy="selectin")


class User(Base):
    __tablename__ = "users"

    id: Mapped[str] = mapped_column(String(36), primary_key=True, default=lambda: str(uuid4()))
    email: Mapped[str] = mapped_column(String(320), unique=True, index=True, nullable=False)
    password_hash: Mapped[str] = mapped_column(String(255), nullable=False)
    # New accounts require manual approval and cannot authenticate until enabled.
    is_active: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False, server_default="false")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class ShoppingListItem(Base):
    """One open entry on a user's shopping list. IDs are generated by the client so offline edits sync idempotently."""

    __tablename__ = "shopping_list_items"
    __table_args__ = (
        Index("ix_shopping_list_items_user_added", "user_id", "added_at"),
        CheckConstraint("amount IS NULL OR amount >= 0", name="ck_shopping_list_items_amount_nonnegative"),
        CheckConstraint(
            "section IN ('produce', 'chilled', 'meat_fish', 'bakery', 'pantry', 'frozen', 'drinks', 'other')",
            name="ck_shopping_list_items_section",
        ),
    )

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    name: Mapped[str] = mapped_column(String(120), nullable=False)
    amount: Mapped[float | None] = mapped_column(Float)
    unit: Mapped[str] = mapped_column(String(32), nullable=False, default="", server_default="")
    section: Mapped[str] = mapped_column(String(16), nullable=False)
    sources: Mapped[list[str]] = mapped_column(JSONB, nullable=False, default=list)
    added_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())


class RecipeSuggestionHistory(Base):
    __tablename__ = "recipe_suggestion_histories"
    __table_args__ = (Index("ix_recipe_suggestion_histories_user_updated", "user_id", "updated_at"),)

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    iterations: Mapped[list[dict[str, object]]] = mapped_column(JSONB, nullable=False, default=list)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())


# --- Cooking events ("Adventskalender"): daily ingredient reveals, then a joint cook day. ---

event_participants = Table(
    "event_participants",
    Base.metadata,
    Column("event_id", Uuid, ForeignKey("events.id", ondelete="CASCADE"), primary_key=True),
    Column("user_id", String(36), ForeignKey("users.id", ondelete="CASCADE"), primary_key=True),
)


class Event(Base):
    __tablename__ = "events"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    creator_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False, index=True)
    title: Mapped[str] = mapped_column(String(200), nullable=False)
    theme: Mapped[str] = mapped_column(Text, nullable=False)
    categories: Mapped[list[str]] = mapped_column(JSONB, nullable=False)
    start_date: Mapped[date] = mapped_column(Date, nullable=False)
    cook_date: Mapped[date] = mapped_column(Date, nullable=False)
    # generating -> active, or failed. Images are produced afterwards (images_pending).
    status: Mapped[str] = mapped_column(String(16), nullable=False, default="generating")
    progress: Mapped[str] = mapped_column(String(200), nullable=False, default="")
    images_pending: Mapped[bool] = mapped_column(Boolean, nullable=False, default=True)
    # Basics everyone is expected to have (salt, oil …); never part of a daily drop.
    pantry: Mapped[list[str]] = mapped_column(JSONB, nullable=False, default=list)
    tip_count: Mapped[int] = mapped_column(Integer, nullable=False, default=0)
    # After the cook day: cooking -> judging -> judged -> finished.
    phase: Mapped[str] = mapped_column(String(16), nullable=False, default="cooking", server_default="cooking")
    verdict: Mapped[dict[str, object] | None] = mapped_column(JSONB)
    jury_error: Mapped[str | None] = mapped_column(Text)
    # Penalty points (tips + jury) are banked when the event is finished; later spent on handicaps.
    penalty_earned: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")
    penalty_spent: Mapped[int] = mapped_column(Integer, nullable=False, default=0, server_default="0")
    # Sorted participant ids: every distinct group of players has its own penalty account.
    team_key: Mapped[str | None] = mapped_column(Text, index=True)
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    # [{handicap, title, ingredient}] actually applied to this event (penalty_spent points).
    handicaps: Mapped[list[dict[str, object]]] = mapped_column(JSONB, nullable=False, default=list, server_default="[]")
    # Cook-day state of interactive handicaps, e.g. {"blind_revealed": true, "memory_started_at": "…"}.
    game_state: Mapped[dict[str, object]] = mapped_column(JSONB, nullable=False, default=dict, server_default="{}")
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    participants: Mapped[list[User]] = relationship(secondary=event_participants, lazy="selectin")


class EventRecipe(Base):
    __tablename__ = "event_recipes"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True)
    category: Mapped[str] = mapped_column(String(40), nullable=False)
    title: Mapped[str] = mapped_column(String(200), nullable=False, index=True)
    # Full RecipeCreate JSON (without image). Instructions are stored but never sent to players.
    recipe: Mapped[dict[str, object]] = mapped_column(JSONB, nullable=False)
    image_data: Mapped[str | None] = mapped_column(Text)


class EventDrop(Base):
    """One player's package for one day: zero or more whole ingredients, or a teaser if empty."""

    __tablename__ = "event_drops"
    __table_args__ = (Index("ix_event_drops_event_user_day", "event_id", "user_id", "day_index", unique=True),)

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    day_index: Mapped[int] = mapped_column(Integer, nullable=False)
    # [{name, amount, unit, image_key}]
    items: Mapped[list[dict[str, object]]] = mapped_column(JSONB, nullable=False, default=list)
    teaser: Mapped[str | None] = mapped_column(Text)
    revealed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))


class EventTip(Base):
    __tablename__ = "event_tips"

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    question: Mapped[str] = mapped_column(Text, nullable=False)
    answer: Mapped[str] = mapped_column(Text, nullable=False)
    # Good Cop, Bad Cop: {"truth": 1|2}, revealed after the event.
    meta: Mapped[dict[str, object] | None] = mapped_column(JSONB)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class IngredientImage(Base):
    """Global, reusable "ingredient on a pedestal" pictures keyed by a normalised ingredient name."""

    __tablename__ = "ingredient_images"

    key: Mapped[str] = mapped_column(String(120), primary_key=True)
    image_data: Mapped[str] = mapped_column(Text, nullable=False)


class EventSubmission(Base):
    """A player's photo of the finished dish plus their own taste rating, judged by the AI jury."""

    __tablename__ = "event_submissions"
    __table_args__ = (Index("ix_event_submissions_unique", "event_id", "user_id", "event_recipe_id", unique=True),)

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    event_recipe_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("event_recipes.id", ondelete="CASCADE"), nullable=False)
    image_data: Mapped[str] = mapped_column(Text, nullable=False)
    taste_rating: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())


class HandicapIconImage(Base):
    """AI-generated icon per handicap. The style sample is stored under id "__preview__" (handicap in `source`)."""

    __tablename__ = "handicap_icons"

    id: Mapped[str] = mapped_column(String(40), primary_key=True)
    image_data: Mapped[str] = mapped_column(Text, nullable=False)
    approved: Mapped[bool] = mapped_column(Boolean, nullable=False, default=False)
    style_hint: Mapped[str] = mapped_column(Text, nullable=False, default="")
    source: Mapped[str] = mapped_column(String(40), nullable=False, default="")


class EventGuess(Base):
    """A player's guess which dish is hidden behind a recipe, made on the cook day before the reveal."""

    __tablename__ = "event_guesses"
    __table_args__ = (Index("ix_event_guesses_unique", "event_id", "user_id", "event_recipe_id", unique=True),)

    id: Mapped[UUID] = mapped_column(Uuid, primary_key=True, default=uuid4)
    event_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("events.id", ondelete="CASCADE"), nullable=False, index=True)
    user_id: Mapped[str] = mapped_column(String(36), ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    event_recipe_id: Mapped[UUID] = mapped_column(Uuid, ForeignKey("event_recipes.id", ondelete="CASCADE"), nullable=False)
    guess: Mapped[str] = mapped_column(String(200), nullable=False)
    correct: Mapped[bool | None] = mapped_column(Boolean)
    reason: Mapped[str | None] = mapped_column(Text)


class TeamSetting(Base):
    """Settings shared by one group of players, e.g. ingredients they must never get (allergies)."""

    __tablename__ = "team_settings"

    team_key: Mapped[str] = mapped_column(Text, primary_key=True)
    exclusions: Mapped[str] = mapped_column(Text, nullable=False, default="")
